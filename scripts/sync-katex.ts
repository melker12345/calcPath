/**
 * Copies KaTeX's stylesheet and woff2 fonts into public/katex/ so the site
 * serves them itself with stable URLs:
 *
 *   - `font-display: block` becomes `swap`, so formulas never sit invisible
 *     while a font loads;
 *   - only the woff2 sources are kept (every supported browser reads woff2),
 *     which drops the woff/ttf fallbacks from the CSS and the copy;
 *   - the file names carry no hash, so the pages can preload the two fonts
 *     nearly every formula needs and next.config can mark them immutable.
 *
 * Run after upgrading katex: npx tsx scripts/sync-katex.ts
 */
import fs from "fs";
import path from "path";

const src = path.join(process.cwd(), "node_modules", "katex", "dist");
const out = path.join(process.cwd(), "public", "katex");
const version = (JSON.parse(fs.readFileSync(path.join(src, "..", "package.json"), "utf8")) as { version: string }).version;

fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(path.join(out, "fonts"), { recursive: true });

let css = fs.readFileSync(path.join(src, "katex.min.css"), "utf8");
css = css.replace(/font-display:block/g, "font-display:swap");
// src:url(fonts/X.woff2) format("woff2"),url(fonts/X.woff) format("woff"),url(fonts/X.ttf) format("truetype")
css = css.replace(/,url\(fonts\/[^)]+\.(?:woff|ttf)\) format\("(?:woff|truetype)"\)/g, "");
fs.writeFileSync(path.join(out, "katex.min.css"), `/* KaTeX ${version} — generated by scripts/sync-katex.ts, do not edit */\n${css}`);

let bytes = 0;
for (const f of fs.readdirSync(path.join(src, "fonts"))) {
  if (!f.endsWith(".woff2")) continue;
  fs.copyFileSync(path.join(src, "fonts", f), path.join(out, "fonts", f));
  bytes += fs.statSync(path.join(out, "fonts", f)).size;
}
fs.writeFileSync(path.join(out, "VERSION"), `${version}\n`);
console.log(`katex ${version}: css ${css.length} B, fonts ${(bytes / 1024).toFixed(0)} KB (woff2 only) → public/katex/`);
